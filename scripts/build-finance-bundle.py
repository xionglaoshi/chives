#!/usr/bin/env python3
"""Build packages/finance-bundle/cordis.patch.yml = MCP overlays + the `finance` agent preset + default-preset override.

Inputs : overlays/*.cordis.yml (failOnStartupError forced to false), presets/finance/{prefix,suffix}.md,
         presets/finance/standard-preset.rc3.yml (snapshot of dsh's shipped `standard` preset).
Output : packages/finance-bundle/cordis.patch.yml  (+ presets/finance/preset-finance.cordis.yml for inspection)
The finance preset is the standard preset with ONLY its persona entry replaced (prefix = identity, suffix = finance rules).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
P = ROOT / "presets/finance"
# A-share focus (T113, 2026-11-16): `openbb`, `fmp` and `x` are no longer assembled. Their overlays and packages are kept;
# to restore one, add its name back to this list (original order: ... "cn-watch", "openbb", "fmp", "tavily", "scrape", "x", "profile" ...) and rebuild.
OVERLAYS = ["cn-market", "cn-data", "cn-extra", "cn-research", "market-watch", "cn-watch", "tavily", "scrape", "profile", "portfolio", "hub", "paper-broker", "trading-guard", "strategy"]
MARK_PERSONA = re.compile(r"      - id: persona\n        name: '@deepseek-ai/dsh-persona'\n        config:\n          prefix: [^\n]*\n")


def block(text: str, indent: int) -> str:
    pad = " " * indent
    return "\n".join((pad + l) if l.strip() else "" for l in text.strip("\n").split("\n"))


def main() -> int:
    prefix = (P / "prefix.md").read_text(encoding="utf-8")
    suffix = (P / "suffix.md").read_text(encoding="utf-8")
    for name, t in (("prefix", prefix), ("suffix", suffix)):
        bad = [m for m in re.findall(r"\{\{[^}]*\}\}", t) if m != "{{model}}"]
        if bad or ("{{" in t and name == "suffix"):
            print(f"{name}.md contains template groups that are not allowed: {bad}", file=sys.stderr)
            return 2
    std = (P / "standard-preset.rc3.yml").read_text(encoding="utf-8")
    std = "\n".join(l for l in std.split("\n") if not l.startswith("#")).strip("\n") + "\n"
    persona = ("      - id: persona\n        name: '@deepseek-ai/dsh-persona'\n        config:\n          prefix: |-\n" + block(prefix, 12)
               + "\n          suffix: |-\n" + block(suffix, 12) + "\n")
    if not MARK_PERSONA.search(std):
        print("persona entry not found in the standard preset snapshot", file=sys.stderr)
        return 2
    preset = MARK_PERSONA.sub(lambda m: persona, std, count=1)
    preset = preset.replace("- id: preset-standard", "- id: preset-finance", 1)
    preset = preset.replace("    id: standard\n    order: 1\n", "    id: finance\n    name: 金融研究\n    description: 金融投资研究智能体：A 股数据、研究报告、盯盘与模拟盘；数据带时间、可给评级与目标价区间、可分析交易计划。\n    order: 0\n", 1)
    assert "id: finance" in preset
    (P / "preset-finance.cordis.yml").write_text(preset, encoding="utf-8")

    parts = []
    for n in OVERLAYS:
        if not (ROOT / "overlays" / f"{n}.cordis.yml").exists():
            print(f"note: overlays/{n}.cordis.yml not found, skipped", file=sys.stderr); continue
        t = (ROOT / "overlays" / f"{n}.cordis.yml").read_text(encoding="utf-8").replace("failOnStartupError: true", "failOnStartupError: false")
        parts.append(f"# ---- {n} ----\n" + t.rstrip() + "\n")
    inserted = "- insert:\n" + "\n".join(("    " + l) if l.strip() else "" for l in preset.rstrip().split("\n")) + "\n"
    parts.append("# ---- finance agent preset (new row, so it goes through insert) ----\n" + inserted)
    parts.append("# ---- finance only: hide the generic presets (standard / ptc / minimal / cordis) ----\n" + "".join(f"- id: preset-{n}\n  disabled: true\n" for n in ("standard", "ptc", "minimal", "cordis")))
    parts.append("# ---- default preset: finance ----\n- id: agent-preset-registry\n  name: '@deepseek-ai/dsh-agent-preset-registry'\n  config:\n    default: finance\n")
    hdr = ("# Chives bundle layer: finance MCP gateways + trading guard + the `finance` agent preset (default).\n"
           "# GENERATED by scripts/build-finance-bundle.py — edit presets/finance/*.md or overlays/, then rebuild.\n"
           "# failOnStartupError=false so a broken gateway never blocks the app.\n")
    (ROOT / "packages/finance-bundle/cordis.patch.yml").write_text(hdr + "\n".join(parts), encoding="utf-8")
    print("built packages/finance-bundle/cordis.patch.yml:", len(prefix), "chars prefix,", len(suffix), "chars suffix")
    return 0


if __name__ == "__main__":
    sys.exit(main())
