export type PixelIcon = keyof typeof drawings;
export const pixelIconIds = Object.keys(drawings) as PixelIcon[];

function drawPixels(drawing: string): string {
  const path: string[] = [];
  for (const [row, pixels] of drawing.split(' ').entries()) {
    for (const run of pixels.matchAll(/#+/g)) {
      const x = 1.5 + run.index * 3;
      const y = 1.5 + row * 3;
      const width = run[0].length * 3;
      path.push(`M${x} ${y}h${width}v3h-${width}z`);
    }
  }
  return path.join(' ');
}

export const pixelIcons = Object.fromEntries(pixelIconIds.map(id => {
  const [label, drawing] = drawings[id];
  return [id, { label, path: drawPixels(drawing) }];
})) as Record<PixelIcon, { label: string; path: string }>;
